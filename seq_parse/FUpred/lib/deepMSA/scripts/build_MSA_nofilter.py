#query    - query sequence
#blastout - psiblast output
#msa      - psiblast MSA file, >seq_name#psi-ev:evalue
#seqid    - sequence identity cutoff
#evalue   - evalue cut off
formatpsiblast_template=Template(bin_dict["formatblast"]+" $query $blastout $msa $seqid $evalue")

#intype     - input file type, fas, a3m etc
#outtype    - output file type, fas, a3m etc
#infile     - input file
#outfile    - output file
#options    - -r, -lc -uc, etc, check reformat.pl for details
